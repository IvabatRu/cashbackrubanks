import type { Bank } from '../data/banks';

/**
 * Переход в приложение банка.
 *
 * Первая попытка была неверной: я собирал намерение «запусти главный экран
 * приложения с таким именем пакета». Так нельзя. Chrome при переходе
 * из интернета принудительно добавляет категорию BROWSABLE и открывает
 * только те экраны, которые явно разрешили открывать себя из веба.
 * Главный экран приложения такого разрешения не имеет, поэтому Chrome
 * ничего не находил и показывал «Файл не найден».
 *
 * Что работать может: у каждого участника СБП есть собственная схема ссылок,
 * зарегистрированная именно для открытия из интернета — по ней работает
 * выбор банка на странице оплаты qr.nspk.ru. Эта схема совпадает с полем
 * schema из реестра НСПК, то есть с нашим id банка ("bank100000000004").
 *
 * Честная оговорка: мы открываем схему без конкретного платежа, поэтому
 * поведение зависит от банка — кто-то откроет главный экран, кто-то
 * сообщение о неверной ссылке. Проверить это можно только на телефоне.
 */

/**
 * Android ли это. Проверяем по строке браузера — способ грубый,
 * но для «показывать кнопку или нет» его достаточно.
 */
export function isAndroid(): boolean {
  if (typeof navigator === 'undefined') return false;
  return /android/i.test(navigator.userAgent);
}

/**
 * Ссылка запуска приложения банка. null — если банк не указал приложение
 * в реестре СБП (таких 35 из 196), тогда кнопку не показываем.
 *
 * Разбор частей:
 *   intent://qr.nspk.ru/ — адрес, который откроет приложение;
 *   scheme=<id банка>    — схема, по которой Android найдёт нужное приложение;
 *   package=<пакет>      — уточнение, какое именно приложение, если
 *                          схему обрабатывает несколько;
 *   S.browser_fallback_url — куда отправить, если приложение не установлено.
 */
export function bankAppUrl(bank: Bank): string | null {
  if (!bank.package) return null;

  const fallback = encodeURIComponent(
    `https://play.google.com/store/apps/details?id=${bank.package}`,
  );

  return [
    'intent://qr.nspk.ru/#Intent',
    `scheme=${bank.id}`,
    `package=${bank.package}`,
    `S.browser_fallback_url=${fallback}`,
    'end',
  ].join(';');
}
